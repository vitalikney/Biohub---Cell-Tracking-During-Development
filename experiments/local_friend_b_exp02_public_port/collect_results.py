"""Copy every post-processing result JSON out of the git-ignored cache into results/ and build one summary table.

The cache (`.public_local_cache/<tag>/pp/<label>.json`) holds the official-metric summary and the per-video
metric rows of every run - a few KB each - while the graphs themselves stay out of git. This puts the numbers
under version control next to the scripts that produced them, per the team rule "one experiment = one folder
with the config and a results JSON".

    python experiments/local_friend_b_exp02_public_port/collect_results.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CACHE = ROOT / ".public_local_cache"
OUT = HERE / "results"

LEAKY_FOR_FT = {"44b6_12dfb391", "44b6_2a2eff9f", "44b6_a21120c2",
                "44b6_c50204e0", "44b6_d2f34f90", "44b6_d5e7d891"}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    rows = []
    for src in sorted(CACHE.glob("*/pp/*.json")):
        tag, label = src.parent.parent.name, src.stem
        dst = OUT / f"{tag}__{label}.json"
        shutil.copy(src, dst)
        d = json.loads(src.read_text())
        s = d["summary"]
        n_raw = sum(v["raw_nodes"] for v in d["per_video"])
        n_out = sum(v["nodes"] for v in d["per_video"])
        clean = sum(1 for v in d["videos"] if v not in LEAKY_FOR_FT)
        rows.append({
            "tag": tag, "label": label, "videos": len(d["videos"]), "clean_videos": clean,
            "primary": d.get("primary") or "pilkwang", "secondary": d.get("secondary") or "seed314159",
            "tta": d.get("tta_group", "public"), "pool_kernel_um": d.get("pool_kernel_um") or 3.0,
            "env": " ".join(d.get("env_overrides", [])),
            "score": s["score"], "adj_edge": s["adj_edge_jaccard"], "edge": s["edge_jaccard"],
            "div_J": s["division_jaccard"],
            "div": f"{int(s['division_tp'])}/{int(s['division_fp'])}/{int(s['division_fn'])}",
            "recall": s["node_recall"], "raw_nodes": n_raw, "out_nodes": n_out,
        })

    (OUT / "all_runs.json").write_text(json.dumps(rows, indent=2))
    lines = ["# All post-processing runs of the local port (official metric)", "",
             "Generated by `collect_results.py` from the run cache. `videos` = how many videos the run scored, "
             "`clean` = how many of them no fine-tuned checkpoint ever trained on (see README, Leakage).", "",
             "| tag | label | videos | clean | primary | secondary | TTA | NMS um | env | score | edge | div_J | div TP/FP/FN | recall | raw nodes | out nodes |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['tag']} | {r['label']} | {r['videos']} | {r['clean_videos']} | {r['primary']} | "
                     f"{r['secondary']} | {r['tta']} | {r['pool_kernel_um']} | {r['env']} | {r['score']:.4f} | "
                     f"{r['edge']:.4f} | {r['div_J']:.4f} | {r['div']} | {r['recall']:.4f} | {r['raw_nodes']} | "
                     f"{r['out_nodes']} |")
    (OUT / "all_runs.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} runs -> {OUT}")
    print("\n".join(lines[5:]))


if __name__ == "__main__":
    main()
