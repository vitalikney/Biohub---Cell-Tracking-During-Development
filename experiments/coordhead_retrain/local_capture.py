def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fetch(dataset: str, remote: str, dest: Path) -> None:
    if dest.is_file():
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp())
    subprocess.run([sys.executable, "-m", "kaggle", "datasets", "download", dataset, "-f", remote, "-p", str(tmp),
                    "--force", "-q"], check=True)
    for z in tmp.glob("*.zip"):
        shutil.unpack_archive(str(z), str(tmp))
        z.unlink()
    got = [p for p in tmp.rglob("*") if p.is_file() and p.name == Path(remote).name]
    if len(got) != 1:
        raise SystemExit(f"download of {dataset}:{remote} failed: {list(tmp.rglob('*'))}")
    shutil.move(str(got[0]), str(dest))
    shutil.rmtree(tmp, ignore_errors=True)


def ensure_assets(assets: Path) -> None:
    for rel, want in REPO_FILES.items():
        fetch(SUPPORT, f"repo/{rel}", assets / "repo" / rel)
        if sha(assets / "repo" / rel) != want:
            raise SystemExit(f"sha256 mismatch {rel}")
    for f in ("edge_predictor_best.pth", "config.json"):
        fetch(SUPPORT, f"weights/{W_REL}/{f}", assets / "repo" / "weights" / W_REL / f)
        fetch(SECONDARY, f"weights/{W_REL}/{f}", assets / "secondary" / W_REL / f)
    fetch(HEAD, "v1284_head.pt", assets / "head" / "v1284_head.pt")
    for p, want in ((assets / "repo" / "weights" / W_REL / "edge_predictor_best.pth", PRIMARY_SHA),
                    (assets / "secondary" / W_REL / "edge_predictor_best.pth", SECONDARY_SHA),
                    (assets / "head" / "v1284_head.pt", HEAD_SHA)):
        if sha(p) != want:
            raise SystemExit(f"sha256 mismatch {p}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", required=True, help="competition train dir with <stem>.zarr and <stem>.geff")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--stems", help="comma-separated train stems")
    g.add_argument("--plan", help="a shard name of capture_plan.json, e.g. s0of4 or pilot")
    g.add_argument("--all", action="store_true", help="all train stems in --data-dir")
    ap.add_argument("--work", required=True)
    ap.add_argument("--assets", default="")
    ap.add_argument("--out", default="", help="capture output dir (default <work>/capture)")
    ap.add_argument("--frames", type=int, default=0, help="SMOKE TEST ONLY: truncated copies with this many frames")
    ap.add_argument("--allow-cpu", action="store_true", help="run a full-length capture without CUDA (very slow)")
    a = ap.parse_args()
    import torch
    print(f"torch {torch.__version__}, CUDA {torch.cuda.is_available()}"
          + (f" ({torch.cuda.get_device_name(0)})" if torch.cuda.is_available() else ""), flush=True)
    if not torch.cuda.is_available() and not a.frames and not a.allow_cpu:
        raise SystemExit("no CUDA device: a full capture needs the GPU (use --frames N for a CPU smoke test)")

    spec = importlib.util.spec_from_file_location("bck", HERE / "build_capture_kernel.py")
    bck = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bck)

    work = Path(a.work).resolve()
    assets = Path(a.assets).resolve() if a.assets else work / "assets"
    out = Path(a.out).resolve() if a.out else work / "capture"
    data_dir = Path(a.data_dir).resolve()
    if a.stems:
        stems, name = [s.strip() for s in a.stems.split(",") if s.strip()], "local"
    elif a.plan:
        stems, name = json.loads((HERE / "capture_plan.json").read_text())[a.plan], a.plan
    else:
        stems, name = sorted(p.name[:-5] for p in data_dir.glob("*.zarr")), "all"
    done = {p.stem for p in out.glob("*.npz")} if out.is_dir() else set()
    todo = [s for s in stems if s not in done]
    print(f"{len(stems)} stems, {len(done & set(stems))} already captured in {out}, {len(todo)} to run", flush=True)
    if not todo:
        return
    ensure_assets(assets)

    run = work / f"run_{name}"
    shutil.rmtree(run, ignore_errors=True)
    comp = run / "input" / "comp"
    (run / "input" / "biohub-v1284-head-s075").mkdir(parents=True)
    (run / "working").mkdir(parents=True)
    shutil.copy(assets / "head" / "v1284_head.pt", run / "input" / "biohub-v1284-head-s075" / "v1284_head.pt")
    shutil.copytree(assets / "repo", run / "working" / "tracking_repo")
    if a.frames:
        import zarr
        (comp / "train").mkdir(parents=True)
        for s in todo:
            src = zarr.open_group(str(data_dir / f"{s}.zarr"), mode="r")
            dst = zarr.open_group(str(comp / "train" / f"{s}.zarr"), mode="w")
            dst.attrs.update(dict(src.attrs))
            arr = dst.create_array("0", shape=(a.frames,) + tuple(src["0"].shape[1:]),
                                   chunks=(1,) + tuple(src["0"].shape[1:]), dtype=src["0"].dtype)
            arr[...] = src["0"][:a.frames]
            shutil.copytree(data_dir / f"{s}.geff", comp / "train" / f"{s}.geff")
    else:
        comp.mkdir(parents=True)
        try:
            os.symlink(data_dir, comp / "train", target_is_directory=True)
        except OSError:  # Windows without symlink rights: a directory junction
            subprocess.run(["cmd", "/c", "mklink", "/J", str(comp / "train"), str(data_dir)], check=True,
                           capture_output=True)

    nb, _ = bck.make_notebook(name, todo)
    cells = ["".join(c["source"]) for c in nb["cells"]]
    raw_dir = run / "raw"

    def redirect(text: str) -> str:
        return (text.replace("/kaggle/working/capture", out.as_posix())
                    .replace("/kaggle/working", (run / "working").as_posix())
                    .replace("/kaggle/input", (run / "input").as_posix())
                    .replace("/tmp/v1284_raw", raw_dir.as_posix()))

    g = {"__name__": "local_capture"}
    exec(compile(redirect(cells[0]), "cell0", "exec"), g)
    working = run / "working"
    g.update({
        "json": json, "os": os, "sys": sys, "time": time, "Path": Path, "subprocess": subprocess,
        "COMP_DIR": comp, "TEST_DIR": comp / "test", "WORKING_DIR": working, "REPO_DIR": working / "tracking_repo",
        "METHOD": "unet_transformer", "WEIGHTS_RELATIVE": f"weights/{W_REL}/edge_predictor_best.pth",
        "UNET_BATCH_SIZE": 4, "DET_THRESHOLD": float(os.environ["BIOHUB_DET_THRESHOLD"]), "USE_ILP": True, "SLICE": "",
        "ILP_EDGE_WEIGHT": -1.0, "ILP_APPEARANCE_WEIGHT": float(os.environ["BIOHUB_ILP_APPEARANCE_WEIGHT"]),
        "ILP_DISAPPEARANCE_WEIGHT": float(os.environ["BIOHUB_ILP_DISAPPEARANCE_WEIGHT"]),
        "ILP_DIVISION_WEIGHT": float(os.environ["BIOHUB_ILP_DIVISION_WEIGHT"]),
    })
    # exp51 cell 3's secondary-model environment
    os.environ["BIOHUB_SECONDARY_WEIGHTS"] = str(assets / "secondary" / W_REL / "edge_predictor_best.pth")
    os.environ.update({"BIOHUB_SECONDARY_EDGE_WEIGHT": "0.15", "BIOHUB_SECONDARY_DETECTION_WEIGHT": "0.80",
                       "BIOHUB_SECONDARY_LINK_MODE": "low_margin_consensus", "BIOHUB_SECONDARY_MIX_TEMPERATURE": "1",
                       "BIOHUB_SECONDARY_LOW_MARGIN_MAX": "0.35", "BIOHUB_DUAL_SEED_EDGE_THRESHOLD": "0.48"})
    os.environ["V1284_CAPTURE_OUT"] = out.as_posix()
    c5 = redirect(cells[5])
    i0 = c5.index('_ps = REPO_DIR / "scripts" / "predict_unet_transformer.py"')
    i1 = c5.index("start_time = time.time()\navailable_gpu_count")
    i2 = c5.index("# ---- coordhead summary (tools/build_probe_kernel.py --patch coordhead) ----")
    # keep earlier captures: the cell clears V1284_CAPTURE_OUT when it patches, so stash them
    stash = work / f"stash_{name}"
    if out.is_dir() and any(out.iterdir()):
        shutil.rmtree(stash, ignore_errors=True)
        shutil.copytree(out, stash)
    exec(compile(c5[i0:i1], "cell5_patches", "exec"), g)
    if stash.is_dir():
        for p in stash.iterdir():
            if not (out / p.name).exists():
                shutil.copy(p, out / p.name)
        shutil.rmtree(stash)
    ps = g["_ps"]
    ps.write_text(redirect(ps.read_text()))
    env = {**os.environ, "PYTHONPATH": "src", "BIOHUB_GPU_SHARD": f"local_{name}"}
    t0 = time.time()
    subprocess.run(list(g["predict_cmd"]), cwd=g["REPO_DIR"], env=env, check=True)
    g.update({"start_time": t0, "predict_seconds": time.time() - t0, "worker_count": 1})
    g["CAPTURE_STEMS"] = [s for s in stems]  # summary checks the whole requested set (resumed stems included)
    exec(compile(c5[i2:], "cell5_summary", "exec"), g)
    print(f"local capture done: {len(todo)} videos in {time.time() - t0:.0f} s -> {out}", flush=True)


if __name__ == "__main__":
    main()
